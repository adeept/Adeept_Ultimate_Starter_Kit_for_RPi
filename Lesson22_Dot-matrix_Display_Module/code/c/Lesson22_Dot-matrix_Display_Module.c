#include <lgpio.h>
#include <stdio.h>

// BCM pins: 17,18,27 (wiringPi 0,1,2)
#define RCLK   17  // Memory clock input (STCP)
#define SRCLK  18  // Shift register clock input (SHCP)
#define SDI    27  // Serial data input

const unsigned char data[] = {
    0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,  // NULL
    0x00,0x00,0x3C,0x42,0x42,0x3C,0x00,0x00,  // 0
    0x00,0x00,0x00,0x44,0x7E,0x40,0x00,0x00,  // 1
    0x00,0x00,0x44,0x62,0x52,0x4C,0x00,0x00,  // 2
    0x00,0x00,0x78,0x14,0x12,0x14,0x78,0x00,  // A
    0x00,0x00,0x60,0x90,0x90,0xFE,0x00,0x00,  // d
    0x00,0x00,0x1C,0x2A,0x2A,0x2A,0x24,0x00,  // e
    0x00,0x00,0x1C,0x2A,0x2A,0x2A,0x24,0x00,  // e
    0x00,0x00,0x7E,0x12,0x12,0x0C,0x00,0x00,  // p
    0x00,0x00,0x08,0x7E,0x88,0x40,0x00,0x00,  // t
    0x3C,0x42,0x95,0xB1,0xB1,0x95,0x42,0x3C,  // :)
    0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00   // NULL
};

const unsigned char tab[] = {0xfe,0xfd,0xfb,0xf7,0xef,0xdf,0xbf,0x7f};

void init(int h)
{
    lgGpioClaimOutput(h, 0, SDI, 0);
    lgGpioClaimOutput(h, 0, RCLK, 0);
    lgGpioClaimOutput(h, 0, SRCLK, 0);
}

void hc595_in(int h, unsigned char dat)
{
    int i;
    for (i = 0; i < 8; i++) {
        lgGpioWrite(h, SDI, (0x80 & (dat << i)) ? 1 : 0);
        lgGpioWrite(h, SRCLK, 1);
        lgGpioWrite(h, SRCLK, 0);
    }
}

void hc595_out(int h)
{
    lgGpioWrite(h, RCLK, 1);
    lgGpioWrite(h, RCLK, 0);
}

int main(void)
{
    int i, j, k;

    int h = lgGpiochipOpen(4);
    if (h < 0) {
        printf("Failed to open gpiochip4, try open gpiochip0\n");
        h = lgGpiochipOpen(0);
        if (h < 0) return -1;
    }

    init(h);

    while (1) {
        for (i = 0; i < (int)(sizeof(data) - 8); i++) {
            for (k = 0; k < 15; k++) {
                for (j = 0; j < 8; j++) {
                    hc595_in(h, data[i + j]);
                    hc595_in(h, tab[j]);
                    hc595_out(h);
                    lguSleep(0.002);
                }
            }
        }
    }

    lgGpiochipClose(h);
    return 0;
}
